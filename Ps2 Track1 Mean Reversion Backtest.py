# 2. Realistic Indian Cash-Equity Delivery Cost Model (Zerodha / NSE Schedule)
# ---------------------------------------------------------------------------
def calc_buy_cost(notional: float) -> float:
    """
    Zerodha NSE Cash-Equity Delivery Buy-Side Statutory Charges + 5 bps Slippage:
      - Brokerage: Rs. 0
      - STT: 0.10% on buy turnover
      - NSE Exchange Txn Charge: 0.00307%
      - SEBI Turnover Fee: 0.0001% (Rs. 10 / crore)
      - Stamp Duty: 0.015% on buy side
      - GST: 18% on (Exchange Txn + SEBI Fee)
      - Slippage: 0.05% (5 bps)
    """
    stt = 0.0010 * notional
    exch = 0.0000307 * notional
    sebi = 0.000001 * notional
    stamp = 0.00015 * notional
    gst = 0.18 * (exch + sebi)
    slippage = 0.0005 * notional
    return stt + exch + sebi + stamp + gst + slippage


def calc_sell_cost(notional: float) -> float:
    """
    Zerodha NSE Cash-Equity Delivery Sell-Side Statutory Charges + DP Charge + 5 bps Slippage:
      - Brokerage: Rs. 0
      - STT: 0.10% on sell turnover
      - NSE Exchange Txn Charge: 0.00307%
      - SEBI Turnover Fee: 0.0001%
      - Stamp Duty: 0.0% on sell side
      - GST: 18% on (Exchange Txn + SEBI Fee)
      - CDSL/Zerodha DP Charge: Rs. 15.34 flat per sell scrip
      - Slippage: 0.05% (5 bps)
    """
    stt = 0.0010 * notional
    exch = 0.0000307 * notional
    sebi = 0.000001 * notional
    gst = 0.18 * (exch + sebi)
    dp_charge = 15.34
    slippage = 0.0005 * notional
    return stt + exch + sebi + gst + dp_charge + slippage


