# 3. Mean Reversion Backtest Engine (Zero Look-Ahead: Signal on Close[t], Fill at Open[t+1])
# ---------------------------------------------------------------------------
def run_mean_reversion_backtest(
    df_full: pd.DataFrame,
    start_date: str,
    end_date: str,
    lookback: int = 20,
    z_entry: float = -1.5,
    z_exit: float = 0.0,
    stop_loss_pct: float = 0.06,
    max_hold_days: int = 15,
    use_trend_filter: bool = False,
    trend_sma_window: int = 100,
    initial_capital: float = 1_000_000.0,
    alloc_pct: float = 0.95,
):
    df = df_full.copy()
    df["SMA"] = df["Close"].rolling(lookback).mean()
    df["STD"] = df["Close"].rolling(lookback).std(ddof=1)
    df["Z_Score"] = (df["Close"] - df["SMA"]) / df["STD"]
    df["BB_Upper_2"] = df["SMA"] + 2.0 * df["STD"]
    df["BB_Lower_2"] = df["SMA"] - 2.0 * df["STD"]
    df["BB_Lower_Entry"] = df["SMA"] + z_entry * df["STD"]

    # RSI-14 for confirmation analysis
    delta = df["Close"].diff()
    gain = delta.clip(lower=0).rolling(14).mean()
    loss = (-delta.clip(upper=0)).rolling(14).mean()
    rs = gain / loss.replace(0, np.nan)
    df["RSI_14"] = 100.0 - (100.0 / (1.0 + rs))

    df["Trend_SMA"] = df["Close"].rolling(trend_sma_window).mean()

    # Slice evaluation window after computing rolling indicators (warm-up from prior history)
    sub = df.loc[start_date:end_date].copy()
    dates = sub.index
    n = len(sub)

    cash = initial_capital
    shares = 0
    entry_price = 0.0
    entry_date = None
    entry_cost = 0.0
    entry_notional = 0.0
    entry_z = 0.0
    hold_days = 0

    pending_action = None  # ("BUY" or "SELL", reason_str, signal_z)
    equity_curve = np.zeros(n)
    position_series = np.zeros(n, dtype=int)
    trades = []

    for i in range(n):
        dt = dates[i]
        row = sub.iloc[i]
        o, h, l, c = row["Open"], row["High"], row["Low"], row["Close"]
        z = row["Z_Score"]

        # 1. Execute pending signal generated at yesterday's close at TODAY'S OPEN
        if pending_action is not None:
            act, reason, sig_z = pending_action
            pending_action = None
            if act == "BUY" and shares == 0:
                target_cash = cash * alloc_pct
                # Estimate shares accounting for buy cost (~0.169%)
                est_shares = int(target_cash // (o * 1.0017))
                if est_shares > 0:
                    notional = est_shares * o
                    b_cost = calc_buy_cost(notional)
                    if notional + b_cost <= cash:
                        cash -= (notional + b_cost)
                        shares = est_shares
                        entry_price = o
                        entry_date = dt
                        entry_cost = b_cost
                        entry_notional = notional
                        entry_z = sig_z
                        hold_days = 0
            elif act == "SELL" and shares > 0:
                notional = shares * o
                s_cost = calc_sell_cost(notional)
                cash += (notional - s_cost)
                gross_pnl = notional - entry_notional
                total_cost = entry_cost + s_cost
                net_pnl = gross_pnl - total_cost
                ret_pct = (net_pnl / (entry_notional + entry_cost)) * 100.0
                trades.append(
                    {
                        "Entry_Date": entry_date.strftime("%Y-%m-%d"),
                        "Exit_Date": dt.strftime("%Y-%m-%d"),
                        "Shares": shares,
                        "Entry_Open": round(entry_price, 2),
                        "Exit_Open": round(o, 2),
                        "Entry_Z": round(entry_z, 2),
                        "Holding_Days": hold_days,
                        "Gross_PnL_INR": round(gross_pnl, 2),
                        "Total_Costs_INR": round(total_cost, 2),
                        "Net_PnL_INR": round(net_pnl, 2),
                        "Net_Return_Pct": round(ret_pct, 2),
                        "Exit_Reason": reason,
                    }
                )
                shares = 0
                entry_price = 0.0
                entry_date = None
                hold_days = 0

        # 2. Mark-to-market portfolio at today's Close
        if shares > 0:
            hold_days += 1
        equity_curve[i] = cash + shares * c
        position_series[i] = 1 if shares > 0 else 0

        # 3. Evaluate EOD signals on today's Close for execution at tomorrow's Open
        if i < n - 1 and not np.isnan(z):
            if shares == 0:
                trend_ok = True
                if use_trend_filter and not np.isnan(row["Trend_SMA"]):
                    # Avoid catching falling knives when price is >4% below 100-day SMA
                    trend_ok = c >= 0.96 * row["Trend_SMA"]
                if z <= z_entry and trend_ok:
                    pending_action = ("BUY", "Z-Score Oversold Entry", z)
            else:
                unrealized_ret = (c - entry_price) / entry_price
                if z >= z_exit:
                    pending_action = ("SELL", "Mean Reversion Exit (Z >= 0)", z)
                elif unrealized_ret <= -stop_loss_pct:
                    pending_action = ("SELL", f"Stop-Loss (-{stop_loss_pct*100:.1f}%)", z)
                elif hold_days >= max_hold_days:
                    pending_action = ("SELL", f"Max Hold ({max_hold_days}d Time Stop)", z)

    # Close any open position at the final bar's close for clean accounting
    if shares > 0:
        dt = dates[-1]
        c = sub.iloc[-1]["Close"]
        notional = shares * c
        s_cost = calc_sell_cost(notional)
        cash += (notional - s_cost)
        gross_pnl = notional - entry_notional
        total_cost = entry_cost + s_cost
        net_pnl = gross_pnl - total_cost
        ret_pct = (net_pnl / (entry_notional + entry_cost)) * 100.0
        trades.append(
            {
                "Entry_Date": entry_date.strftime("%Y-%m-%d"),
                "Exit_Date": dt.strftime("%Y-%m-%d"),
                "Shares": shares,
                "Entry_Open": round(entry_price, 2),
                "Exit_Open": round(c, 2),
                "Entry_Z": round(entry_z, 2),
                "Holding_Days": hold_days,
                "Gross_PnL_INR": round(gross_pnl, 2),
                "Total_Costs_INR": round(total_cost, 2),
                "Net_PnL_INR": round(net_pnl, 2),
                "Net_Return_Pct": round(ret_pct, 2),
                "Exit_Reason": "End of Period Mark-to-Market",
            }
        )
        equity_curve[-1] = cash
        shares = 0

    sub["Equity"] = equity_curve
    sub["Position"] = position_series
    sub["Daily_Return"] = sub["Equity"].pct_change().fillna(0.0)
    sub["Peak_Equity"] = sub["Equity"].cummax()
    sub["Drawdown_Pct"] = ((sub["Equity"] - sub["Peak_Equity"]) / sub["Peak_Equity"]) * 100.0

    return sub, pd.DataFrame(trades)


def compute_metrics(
    sub: pd.DataFrame,
    trades_df: pd.DataFrame,
    bench_series: pd.Series,
    rf_annual: float = 0.065,
    initial_capital: float = 1_000_000.0,
) -> dict:
    """Computes all required CFA Club PS2 Section 2.7.3 performance metrics."""
    n_days = len(sub)
    final_eq = sub["Equity"].iloc[-1]
    cum_ret_pct = ((final_eq / initial_capital) - 1.0) * 100.0
    years = n_days / 252.0
    ann_ret_pct = (((final_eq / initial_capital) ** (1.0 / years)) - 1.0) * 100.0

    daily_rets = sub["Daily_Return"].values
    rf_daily = (1.0 + rf_annual) ** (1.0 / 252.0) - 1.0
    excess_rets = daily_rets - rf_daily

    std_daily = np.std(daily_rets, ddof=1)
    sharpe = (np.mean(excess_rets) / std_daily) * np.sqrt(252.0) if std_daily > 1e-9 else np.nan

    downside_diff = np.minimum(0.0, excess_rets)
    downside_dev = np.sqrt(np.mean(downside_diff ** 2))
    sortino = (np.mean(excess_rets) / downside_dev) * np.sqrt(252.0) if downside_dev > 1e-9 else np.nan

    max_dd_pct = sub["Drawdown_Pct"].min()

    # Benchmark over exact same dates
    b_sub = bench_series.loc[sub.index[0] : sub.index[-1]]
    b_cum_ret_pct = ((b_sub.iloc[-1] / b_sub.iloc[0]) - 1.0) * 100.0
    b_ann_ret_pct = (((b_sub.iloc[-1] / b_sub.iloc[0]) ** (1.0 / years)) - 1.0) * 100.0
    b_daily_rets = b_sub.pct_change().fillna(0.0).values
    b_std = np.std(b_daily_rets, ddof=1)
    b_sharpe = (np.mean(b_daily_rets - rf_daily) / b_std) * np.sqrt(252.0) if b_std > 1e-9 else np.nan
    b_dd_pct = (((b_sub - b_sub.cummax()) / b_sub.cummax()) * 100.0).min()

    # Underlying Stock Buy & Hold over exact same dates
    s_cum_ret_pct = ((sub["Close"].iloc[-1] / sub["Close"].iloc[0]) - 1.0) * 100.0
    s_ann_ret_pct = (((sub["Close"].iloc[-1] / sub["Close"].iloc[0]) ** (1.0 / years)) - 1.0) * 100.0

    n_trades = len(trades_df)
    if n_trades > 0:
        wins = trades_df[trades_df["Net_PnL_INR"] > 0]
        losses = trades_df[trades_df["Net_PnL_INR"] <= 0]
        win_rate = (len(wins) / n_trades) * 100.0
        gross_profit = wins["Net_PnL_INR"].sum() if len(wins) > 0 else 0.0
        gross_loss = abs(losses["Net_PnL_INR"].sum()) if len(losses) > 0 else 0.0
        profit_factor = round(gross_profit / gross_loss, 2) if gross_loss > 0 else "N/A (No Losing Trades)"
        avg_profit_pct = round(wins["Net_Return_Pct"].mean(), 2) if len(wins) > 0 else 0.0
        avg_profit_inr = round(wins["Net_PnL_INR"].mean(), 2) if len(wins) > 0 else 0.0
        avg_loss_pct = round(losses["Net_Return_Pct"].mean(), 2) if len(losses) > 0 else 0.0
        avg_loss_inr = round(losses["Net_PnL_INR"].mean(), 2) if len(losses) > 0 else 0.0
        max_profit_pct = round(trades_df["Net_Return_Pct"].max(), 2)
        max_profit_inr = round(trades_df["Net_PnL_INR"].max(), 2)
        max_loss_pct = round(trades_df["Net_Return_Pct"].min(), 2)
        max_loss_inr = round(trades_df["Net_PnL_INR"].min(), 2)
        total_costs_inr = round(trades_df["Total_Costs_INR"].sum(), 2)
        avg_hold_days = round(trades_df["Holding_Days"].mean(), 1)
    else:
        win_rate = 0.0
        profit_factor = "N/A"
        avg_profit_pct = avg_profit_inr = avg_loss_pct = avg_loss_inr = 0.0
        max_profit_pct = max_profit_inr = max_loss_pct = max_loss_inr = 0.0
        total_costs_inr = 0.0
        avg_hold_days = 0.0

    return {
        "Trading_Days": int(n_days),
        "Final_Equity_INR": round(final_eq, 2),
        "Cumulative_Return_Pct": round(cum_ret_pct, 2),
        "Annualized_Return_Pct": round(ann_ret_pct, 2),
        "Sharpe_Ratio": round(sharpe, 2),
        "Sortino_Ratio": round(sortino, 2),
        "Max_Drawdown_Pct": round(max_dd_pct, 2),
        "Total_Trades": int(n_trades),
        "Win_Rate_Pct": round(win_rate, 2),
        "Profit_Factor": profit_factor,
        "Avg_Profit_Pct": avg_profit_pct,
        "Avg_Profit_INR": avg_profit_inr,
        "Avg_Loss_Pct": avg_loss_pct,
        "Avg_Loss_INR": avg_loss_inr,
        "Max_Profit_Pct": max_profit_pct,
        "Max_Profit_INR": max_profit_inr,
        "Max_Loss_Pct": max_loss_pct,
        "Max_Loss_INR": max_loss_inr,
        "Total_Transaction_Costs_INR": total_costs_inr,
        "Avg_Holding_Days": avg_hold_days,
        "Benchmark_Cum_Return_Pct": round(b_cum_ret_pct, 2),
        "Benchmark_Ann_Return_Pct": round(b_ann_ret_pct, 2),
        "Benchmark_Sharpe": round(b_sharpe, 2),
        "Benchmark_Max_DD_Pct": round(b_dd_pct, 2),
        "Stock_BH_Cum_Return_Pct": round(s_cum_ret_pct, 2),
        "Stock_BH_Ann_Return_Pct": round(s_ann_ret_pct, 2),
    }


def main():
    os.makedirs("artifacts/file_generation/ttl=63d/intermediate", exist_ok=True)
    os.makedirs("artifacts/file_generation/ttl=63d/output", exist_ok=True)

    rel_c = parse_series(RELIANCE_RAW, "Close")
    nifty_c = parse_series(NIFTY50_RAW, "Nifty_Close")
    hdfc_c = parse_series(HDFCBANK_RAW, "Close")

    # Align common trading dates
    common_idx = rel_c.index.intersection(nifty_c.index).intersection(hdfc_c.index)
    rel_df = construct_ohlcv(rel_c.loc[common_idx, "Close"], base_vol=14_500_000, seed=42)
    hdfc_df = construct_ohlcv(hdfc_c.loc[common_idx, "Close"], base_vol=18_500_000, seed=101)
    nifty_s = nifty_c.loc[common_idx, "Nifty_Close"]

    # Save combined dataset CSV to intermediate for reference
    combined_csv = rel_df.copy()
    combined_csv["Nifty50_Close"] = nifty_s
    combined_csv["HDFCBank_Close"] = hdfc_df["Close"]
    combined_csv.to_csv("artifacts/file_generation/ttl=63d/intermediate/nse_reliance_hdfc_nifty_2024_2026.csv")

    # Define Development (In-Sample) vs Unseen Test (Out-of-Sample) periods
    # Development: 2024-02-01 to 2025-06-30 (after 20-day indicator warm-up in Jan 2024)
    # Unseen Test: 2025-07-01 to 2026-10-23
    dev_start, dev_end = "2024-02-01", "2025-06-30"
    test_start, test_end = "2025-07-01", "2026-10-23"
    full_start, full_end = "2024-02-01", "2026-10-23"

    # Run backtests
    sub_dev, trades_dev = run_mean_reversion_backtest(rel_df, dev_start, dev_end)
    sub_test, trades_test = run_mean_reversion_backtest(rel_df, test_start, test_end)
    sub_test_filt, trades_test_filt = run_mean_reversion_backtest(
        rel_df, test_start, test_end, use_trend_filter=True, trend_sma_window=100
    )
    sub_full, trades_full = run_mean_reversion_backtest(rel_df, full_start, full_end)
    sub_hdfc_test, trades_hdfc_test = run_mean_reversion_backtest(hdfc_df, test_start, test_end)

    m_dev = compute_metrics(sub_dev, trades_dev, nifty_s)
    m_test = compute_metrics(sub_test, trades_test, nifty_s)
    m_test_filt = compute_metrics(sub_test_filt, trades_test_filt, nifty_s)
    m_full = compute_metrics(sub_full, trades_full, nifty_s)
    m_hdfc_test = compute_metrics(sub_hdfc_test, trades_hdfc_test, nifty_s)

    # Parameter sensitivity grid on Unseen Test Period (Lookback N vs Z_entry)
    lookbacks = [10, 15, 20, 25, 30]
    z_entries = [-1.25, -1.50, -1.75, -2.00]
    sens_ret = np.zeros((len(lookbacks), len(z_entries)))
    sens_sharpe = np.zeros((len(lookbacks), len(z_entries)))
    for r_i, lb in enumerate(lookbacks):
        for c_i, ze in enumerate(z_entries):
            s_tmp, t_tmp = run_mean_reversion_backtest(rel_df, test_start, test_end, lookback=lb, z_entry=ze)
            m_tmp = compute_metrics(s_tmp, t_tmp, nifty_s)
            sens_ret[r_i, c_i] = m_tmp["Cumulative_Return_Pct"]
            sens_sharpe[r_i, c_i] = m_tmp["Sharpe_Ratio"] if not np.isnan(m_tmp["Sharpe_Ratio"]) else -2.0

    summary = {
        "Development_Period_2024_02_to_2025_06": m_dev,
        "Unseen_Test_Base_2025_07_to_2026_10": m_test,
        "Unseen_Test_TrendFiltered_2025_07_to_2026_10": m_test_filt,
        "Full_Period_2024_02_to_2026_10": m_full,
        "HDFCBank_Unseen_Test_2025_07_to_2026_10": m_hdfc_test,
        "Dev_Trades": trades_dev.to_dict(orient="records"),
        "Test_Trades": trades_test.to_dict(orient="records"),
        "Test_Filtered_Trades": trades_test_filt.to_dict(orient="records"),
    }

    with open("artifacts/file_generation/ttl=63d/intermediate/backtest_summary.json", "w") as f:
        json.dump(summary, f, indent=2)

    print("=== BACKTEST SUMMARY ===")
    for k in [
        "Development_Period_2024_02_to_2025_06",
        "Unseen_Test_Base_2025_07_to_2026_10",
        "Unseen_Test_TrendFiltered_2025_07_to_2026_10",
        "HDFCBank_Unseen_Test_2025_07_to_2026_10",
    ]:
        print(f"\n--- {k} ---")
        for mk, mv in summary[k].items():
            print(f"  {mk}: {mv}")

    # -----------------------------------------------------------------------
    # 4. Generate Publication-Grade Charts (180 DPI)
    # -----------------------------------------------------------------------
    plt.rcParams["font.sans-serif"] = "DejaVu Sans"
    plt.rcParams["axes.edgecolor"] = "#CBD5E1"
    plt.rcParams["axes.linewidth"] = 0.8

    # FIGURE 1: Price, Bollinger Bands, Trade Markers & Z-Score Signal
    fig, (ax1, ax2) = plt.subplots(
        2, 1, figsize=(11.5, 6.8), gridspec_kw={"height_ratios": [2.3, 1.1]}, sharex=True
    )
    fig.patch.set_facecolor("#FFFFFF")

    ax1.plot(sub_full.index, sub_full["Close"], color="#0F172A", lw=1.4, label="RELIANCE.NS Close (INR)")
    ax1.plot(sub_full.index, sub_full["SMA"], color="#1D4ED8", lw=1.2, ls="--", label="20-Day SMA Reference")
    ax1.fill_between(
        sub_full.index,
        sub_full["BB_Lower_2"],
        sub_full["BB_Upper_2"],
        color="#93C5FD",
        alpha=0.22,
        label="Bollinger Band (±2.0σ)",
    )

    # Plot trade entries & exits
    for tr in trades_full.to_dict(orient="records"):
        ed = pd.to_datetime(tr["Entry_Date"])
        xd = pd.to_datetime(tr["Exit_Date"])
        ax1.scatter(ed, tr["Entry_Open"], marker="^", color="#059669", s=65, zorder=5)
        ax1.scatter(xd, tr["Exit_Open"], marker="v", color="#DC2626", s=65, zorder=5)

    # Dummy scatters for legend
    ax1.scatter([], [], marker="^", color="#059669", s=65, label="Buy Entry (Next Open, Z ≤ -1.5)")
    ax1.scatter([], [], marker="v", color="#DC2626", s=65, label="Sell Exit (Z ≥ 0 / Stop / 15d)")

    split_dt = pd.to_datetime("2025-07-01")
    ax1.axvline(split_dt, color="#D97706", lw=1.5, ls="-.")
    ax1.text(
        split_dt,
        1145.0,
        "  Out-of-Sample Test Starts (1 Jul 2025)",
        color="#B45309",
        fontsize=9,
        fontweight="bold",
        va="bottom",
    )
    ax1.set_title(
        "Reliance Industries (NSE: RELIANCE) — Mean Reversion Signals, Bollinger Bands & Trade Executions (2024–2026)",
        fontsize=11.5,
        fontweight="bold",
        color="#0F172A",
        pad=10,
    )
    ax1.set_ylabel("Price (INR)", fontsize=9.5, fontweight="bold", color="#1E293B")
    ax1.legend(loc="upper left", frameon=True, facecolor="#F8FAFC", fontsize=8.2, ncol=3)
    ax1.grid(True, linestyle=":", alpha=0.5, color="#CBD5E1")

    # Panel 2: Rolling Z-Score
    ax2.plot(sub_full.index, sub_full["Z_Score"], color="#334155", lw=1.1, label="20-Day Rolling Z-Score")
    ax2.axhline(0.0, color="#1D4ED8", lw=1.0, ls="--", label="Mean Exit (Z = 0.0)")
    ax2.axhline(-1.5, color="#059669", lw=1.2, ls="-", label="Oversold Entry (Z = -1.5)")
    ax2.axhline(1.5, color="#94A3B8", lw=0.9, ls=":")
    ax2.axvline(split_dt, color="#D97706", lw=1.5, ls="-.")
    ax2.fill_between(
        sub_full.index,
        sub_full["Z_Score"],
        -1.5,
        where=(sub_full["Z_Score"] <= -1.5),
        color="#10B981",
        alpha=0.28,
    )
    ax2.set_ylabel("Z-Score (σ)", fontsize=9.5, fontweight="bold", color="#1E293B")
    ax2.set_xlabel("Trading Date", fontsize=9.5, fontweight="bold", color="#1E293B")
    ax2.legend(loc="upper right", frameon=True, facecolor="#F8FAFC", fontsize=8.2, ncol=3)
    ax2.grid(True, linestyle=":", alpha=0.5, color="#CBD5E1")
    ax2.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))

    plt.tight_layout()
    fig.savefig("artifacts/file_generation/ttl=63d/intermediate/fig1_price_bollinger_signals.png", dpi=180, bbox_inches="tight")
    plt.close(fig)

    # FIGURE 2: Equity Curve (Strategy vs NIFTY 50 vs RELIANCE B&H) & Drawdown Chart
    fig, (ax1, ax2) = plt.subplots(
        2, 1, figsize=(11.5, 6.6), gridspec_kw={"height_ratios": [2.1, 1.1]}, sharex=True
    )
    fig.patch.set_facecolor("#FFFFFF")

    # Normalize NIFTY 50 and RELIANCE B&H to ₹10,00,000 at start of Development (2024-02-01)
    nifty_full = nifty_s.loc[sub_full.index]
    nifty_eq = 1_000_000.0 * (nifty_full / nifty_full.iloc[0])
    rel_bh_eq = 1_000_000.0 * (sub_full["Close"] / sub_full["Close"].iloc[0])

    # Also build combined curve where Test uses the Trend-Filtered variation after 2025-07-01
    eq_filt_combined = sub_full["Equity"].copy()
    scale_factor = sub_dev["Equity"].iloc[-1] / 1_000_000.0
    eq_filt_combined.loc[sub_test_filt.index] = sub_test_filt["Equity"] * scale_factor

    ax1.plot(sub_full.index, sub_full["Equity"] / 1e5, color="#1D4ED8", lw=1.8, label="Mean Reversion Strategy (Base Z ≤ -1.5)")
    ax1.plot(sub_full.index, eq_filt_combined / 1e5, color="#059669", lw=1.6, ls="--", label="Mean Reversion + 100d Trend Filter")
    ax1.plot(sub_full.index, nifty_eq / 1e5, color="#64748B", lw=1.4, label="NIFTY 50 Benchmark (Buy & Hold)")
    ax1.plot(sub_full.index, rel_bh_eq / 1e5, color="#94A3B8", lw=1.1, ls=":", label="RELIANCE.NS (Buy & Hold)")
    ax1.axvline(split_dt, color="#D97706", lw=1.5, ls="-.")
    ax1.text(
        split_dt,
        8.25,
        "  Unseen Test Period →",
        color="#B45309",
        fontsize=9,
        fontweight="bold",
        va="bottom",
    )
    ax1.set_title(
        "Portfolio Equity Curve (₹ Lakhs, Initial Capital ₹10.00L) & Underwater Drawdown Profile (Net of Costs)",
        fontsize=11.5,
        fontweight="bold",
        color="#0F172A",
        pad=10,
    )
    ax1.set_ylabel("Portfolio Value (₹ Lakhs)", fontsize=9.5, fontweight="bold", color="#1E293B")
    ax1.legend(loc="upper left", frameon=True, facecolor="#F8FAFC", fontsize=8.3, ncol=2)
    ax1.grid(True, linestyle=":", alpha=0.5, color="#CBD5E1")

    nifty_dd = ((nifty_eq - nifty_eq.cummax()) / nifty_eq.cummax()) * 100.0
    ax2.plot(sub_full.index, sub_full["Drawdown_Pct"], color="#DC2626", lw=1.3, label="Strategy Drawdown (%)")
    ax2.fill_between(sub_full.index, sub_full["Drawdown_Pct"], 0, color="#FCA5A5", alpha=0.35)
    ax2.plot(sub_full.index, nifty_dd, color="#64748B", lw=1.1, ls="--", label="NIFTY 50 Drawdown (%)")
    ax2.axvline(split_dt, color="#D97706", lw=1.5, ls="-.")
    ax2.set_ylabel("Drawdown (%)", fontsize=9.5, fontweight="bold", color="#1E293B")
    ax2.set_xlabel("Trading Date", fontsize=9.5, fontweight="bold", color="#1E293B")
    ax2.legend(loc="lower left", frameon=True, facecolor="#F8FAFC", fontsize=8.3, ncol=2)
    ax2.grid(True, linestyle=":", alpha=0.5, color="#CBD5E1")
    ax2.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))

    plt.tight_layout()
    fig.savefig("artifacts/file_generation/ttl=63d/intermediate/fig2_equity_and_drawdown.png", dpi=180, bbox_inches="tight")
    plt.close(fig)

    # FIGURE 3: Parameter Sensitivity Heatmap & Cross-Stock Robustness (RELIANCE vs HDFCBANK)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.5, 4.4), gridspec_kw={"width_ratios": [1.15, 1.0]})
    fig.patch.set_facecolor("#FFFFFF")

    im = ax1.imshow(sens_ret, cmap="RdYlGn", aspect="auto")
    ax1.set_xticks(range(len(z_entries)))
    ax1.set_xticklabels([f"Z ≤ {z:.2f}" for z in z_entries], fontsize=9)
    ax1.set_yticks(range(len(lookbacks)))
    ax1.set_yticklabels([f"N = {lb}d" for lb in lookbacks], fontsize=9)
    for r_i in range(len(lookbacks)):
        for c_i in range(len(z_entries)):
            val = sens_ret[r_i, c_i]
            sh = sens_sharpe[r_i, c_i]
            txt_color = "#0F172A" if abs(val) < 10 else "#FFFFFF"
            ax1.text(
                c_i,
                r_i,
                f"{val:+.1f}%\n(SR: {sh:.2f})",
                ha="center",
                va="center",
                fontsize=8.2,
                fontweight="bold",
                color=txt_color,
            )
    ax1.set_title("Unseen Test Return (%) & Sharpe Grid\n(RELIANCE.NS Across Lookback N & Entry Z)", fontsize=10.5, fontweight="bold", color="#0F172A")
    ax1.set_xlabel("Oversold Entry Z-Score Threshold", fontsize=9, fontweight="bold")
    ax1.set_ylabel("SMA Lookback Window (Days)", fontsize=9, fontweight="bold")
    fig.colorbar(im, ax=ax1, fraction=0.046, pad=0.04, label="Net Cumulative Return (%)")

    # Right panel: Cross-Stock & Regime Comparison Bar Chart on Unseen Test Period (Jul 2025 - Oct 2026)
    labels = [
        "RELIANCE\nBase Mean Rev",
        "RELIANCE\n+Trend Filter",
        "RELIANCE\nBuy & Hold",
        "HDFCBANK\nBase Mean Rev",
        "NIFTY 50\nBenchmark",
    ]
    vals = [
        m_test["Cumulative_Return_Pct"],
        m_test_filt["Cumulative_Return_Pct"],
        m_test["Stock_BH_Cum_Return_Pct"],
        m_hdfc_test["Cumulative_Return_Pct"],
        m_test["Benchmark_Cum_Return_Pct"],
    ]
    bar_colors = [
        "#1D4ED8" if v >= 0 else "#DC2626" for v in vals
    ]
    bars = ax2.bar(labels, vals, color=bar_colors, width=0.55, edgecolor="#0F172A", linewidth=0.6)
    ax2.axhline(0, color="#0F172A", lw=0.9)
    for b, v in zip(bars, vals):
        y_pos = v + (0.8 if v >= 0 else -1.8)
        ax2.text(
            b.get_x() + b.get_width() / 2.0,
            y_pos,
            f"{v:+.2f}%",
            ha="center",
            va="bottom" if v >= 0 else "top",
            fontsize=8.5,
            fontweight="bold",
            color="#0F172A",
        )
    ax2.set_ylim(min(vals) - 5.0, max(vals) + 5.0)
    ax2.set_title("Out-of-Sample Test Performance Comparison\n(1 Jul 2025 – 23 Oct 2026, Net of Costs)", fontsize=10.5, fontweight="bold", color="#0F172A")
    ax2.set_ylabel("Cumulative Net Return (%)", fontsize=9, fontweight="bold")
    ax2.grid(True, axis="y", linestyle=":", alpha=0.5, color="#CBD5E1")
    ax2.tick_params(axis="x", labelsize=8.2)

    plt.tight_layout()
    fig.savefig("artifacts/file_generation/ttl=63d/intermediate/fig3_sensitivity_and_robustness.png", dpi=180, bbox_inches="tight")
    plt.close(fig)
    print("Saved all 3 figures successfully.")


if __name__ == "__main__":
    main()