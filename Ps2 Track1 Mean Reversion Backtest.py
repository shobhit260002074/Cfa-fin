def parse_series(raw_text: str, col_name: str) -> pd.DataFrame:
    rows = []
    for line in raw_text.strip().splitlines():
        if not line.strip():
            continue
        dt_str, val_str = line.strip().split(",")
        rows.append((pd.to_datetime(dt_str), float(val_str)))
    df = pd.DataFrame(rows, columns=["Date", col_name]).drop_duplicates("Date").sort_values("Date")
    return df.set_index("Date")


def construct_ohlcv(close_series: pd.Series, base_vol: int, seed: int) -> pd.DataFrame:
    """
    Constructs realistic daily OHLCV bars anchored to the exact verified daily closing
    prices from Google Finance (split-adjusted for 1:1 bonus actions).
    Open[t] reflects overnight gap from Close[t-1] plus small market open drift.
    """
    rng = np.random.default_rng(seed)
    closes = close_series.values
    n = len(closes)
    opens = np.zeros(n)
    highs = np.zeros(n)
    lows = np.zeros(n)
    vols = np.zeros(n, dtype=np.int64)

    opens[0] = round(closes[0] * 0.998, 2)
    for i in range(1, n):
        # Overnight gap is ~25% of the day's close-to-close move + small microstructure noise
        ret = (closes[i] - closes[i - 1]) / closes[i - 1]
        overnight_gap = 0.22 * ret + rng.normal(0.0, 0.0012)
        opens[i] = round(closes[i - 1] * (1.0 + overnight_gap), 2)

    for i in range(n):
        body_high = max(opens[i], closes[i])
        body_low = min(opens[i], closes[i])
        body_range = abs(closes[i] - opens[i])
        wick_up = max(closes[i] * 0.0025, body_range * rng.uniform(0.25, 0.65))
        wick_dn = max(closes[i] * 0.0025, body_range * rng.uniform(0.25, 0.65))
        highs[i] = round(body_high + wick_up, 2)
        lows[i] = round(body_low - wick_dn, 2)
        rel_move = abs(closes[i] - opens[i]) / closes[i]
        vol_mult = 1.0 + 35.0 * rel_move + rng.uniform(-0.18, 0.22)
        vols[i] = int(max(base_vol * 0.45, base_vol * vol_mult))

    return pd.DataFrame(
        {
            "Open": opens,
            "High": highs,
            "Low": lows,
            "Close": closes,
            "Volume": vols,
        },
        index=close_series.index,
    )


